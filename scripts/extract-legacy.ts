/**
 * Generates the typed content modules in `src/content/` from the legacy
 * tracker in `index.html`.
 *
 *   node scripts/extract-legacy.ts          write the files
 *   node scripts/extract-legacy.ts --check  fail if the files are out of date
 *
 * Runs on plain Node 22 (type stripping), with no dependencies.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { analyzeLegacy, type LegacyAnalysis, type RawPaper } from "./legacy/analyze.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "content");

/** Legacy prompt-building function name to the rebuild's prompt id. */
export const PROMPT_IDS: Readonly<Record<string, string>> = {
  genReview: "reviewWeaknesses",
  genNote: "writeNote",
  genQuiz: "writeQuiz",
  submitQuiz: "markQuiz",
  markAnswer: "markAnswer",
  genToday: "todaysSeven",
};

const header = (a: LegacyAnalysis): string =>
  [
    "// GENERATED by scripts/extract-legacy.ts from index.html. Do not edit by hand.",
    "// Run `npm run content:extract` after changing index.html.",
    `// Source sha256: ${a.sourceSha256}`,
    "",
  ].join("\n");

const json = (v: unknown): string => JSON.stringify(v, null, 2);

function specModule(a: LegacyAnalysis): string {
  const subjects = a.subjects.map((s) => {
    let topicIndex = 0;
    return {
      id: s.id,
      name: s.name,
      board: s.board,
      code: s.code,
      papers: s.papers.map((p) => ({
        name: p.n,
        topics: p.t.map(([name, points]) => {
          const id = `${s.id}.${topicIndex++}`;
          return { id, name, points: points.map((text, i) => ({ id: `${id}.${i}`, text })) };
        }),
      })),
    };
  });
  return `${header(a)}
import type { Subject } from "./types";

export const SPEC: readonly Subject[] = ${json(subjects)};
`;
}

function papersModule(a: LegacyAnalysis): string {
  const out: Record<string, unknown[]> = {};
  for (const [sid, list] of Object.entries(a.papers)) {
    out[sid] = list.map((p: RawPaper) => {
      const url = a.paperUrls[p.k];
      if (!url) throw new Error(`Paper ${p.k} has no URL in PURL`);
      return { key: p.k, title: p.t, group: p.g, pages: p.pg, marks: p.mk, url };
    });
  }
  return `${header(a)}
import type { PracticePaper, SubjectId } from "./types";

export const PAPERS: Readonly<Partial<Record<SubjectId, readonly PracticePaper[]>>> = ${json(out)};
`;
}

function promptsModule(a: LegacyAnalysis): string {
  const prompts: Record<string, unknown> = {};
  for (const p of a.prompts) {
    const id = PROMPT_IDS[p.fn];
    if (!id) throw new Error(`No prompt id for legacy function ${p.fn}`);
    if (prompts[id]) throw new Error(`Duplicate prompt ${id}`);
    prompts[id] = {
      id,
      legacyFunction: p.fn,
      line: p.line,
      functionLines: p.functionLines,
      quasis: p.quasis,
      exprs: p.exprs,
      call: p.call,
    };
  }
  const missing = Object.values(PROMPT_IDS).filter((id) => !prompts[id]);
  if (missing.length) throw new Error(`Prompts not found: ${missing.join(", ")}`);
  return `${header(a)}
import type { LegacyPrompt, PromptId } from "./types";

export const LEGACY_PROMPTS: Readonly<Record<PromptId, LegacyPrompt>> = ${json(prompts)};
`;
}

function legacyMapModule(a: LegacyAnalysis): string {
  return `${header(a)}
import type { LegacyAction, LegacyFunctionInfo, LegacyView } from "./types";

export const LEGACY_SOURCE_SHA256 = ${json(a.sourceSha256)};

export const LEGACY_ACTIONS: readonly LegacyAction[] = ${json(a.actions)};

export const LEGACY_VIEWS: readonly LegacyView[] = ${json(a.views)};

export const LEGACY_FUNCTIONS: readonly LegacyFunctionInfo[] = ${json(
    a.functions.map(({ name, startLine, endLine }) => ({ name, startLine, endLine })),
  )};

/** Allowed SVG tags in note images (legacy \`SVG_TAGS\`). */
export const SVG_TAGS: readonly string[] = ${json(a.sanitiser.svgTags)};

/** Allowed SVG attributes in note images (legacy \`SVG_ATTR\`). */
export const SVG_ATTRS: readonly string[] = ${json(a.sanitiser.svgAttrs)};

/** Allowed fill/stroke values in note images (legacy \`SAFE_PAINT\`). */
export const SAFE_PAINT: RegExp = ${a.sanitiser.safePaint};

/** Poem annotation keys and labels (legacy \`PMK\`). */
export const POEM_MARK_KEYS: Readonly<Record<string, string>> = ${json(a.poemMarkKeys)};

/** Spaced-review intervals in days (legacy \`INT\`). */
export const REVIEW_INTERVALS: readonly number[] = ${json(a.reviewIntervals)};
`;
}

export function generate(html: string): Record<string, string> {
  const a = analyzeLegacy(html);
  return {
    "spec.ts": specModule(a),
    "papers.ts": papersModule(a),
    "prompts.ts": promptsModule(a),
    "legacy-map.ts": legacyMapModule(a),
  };
}

function main(): void {
  const check = process.argv.includes("--check");
  const files = generate(readFileSync(join(ROOT, "index.html"), "utf8"));
  const stale: string[] = [];
  for (const [name, content] of Object.entries(files)) {
    const path = join(OUT, name);
    if (check) {
      let current = "";
      try {
        current = readFileSync(path, "utf8");
      } catch {
        // missing counts as stale
      }
      if (current !== content) stale.push(relative(ROOT, path));
    } else {
      writeFileSync(path, content);
      console.log(`wrote ${relative(ROOT, path)}`);
    }
  }
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run npm run content:extract.`);
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
