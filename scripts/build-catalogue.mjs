/**
 * Writes src/content/extra-specs.ts, which imports every spec in
 * content/specs/*.json. Run it after adding or removing a spec file:
 *   node scripts/build-catalogue.mjs          (write)
 *   node scripts/build-catalogue.mjs --check  (fail if out of date)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = readdirSync(join(root, "content", "specs"))
  .filter((f) => f.endsWith(".json"))
  .sort();

const lines = [
  "// GENERATED by scripts/build-catalogue.mjs from content/specs/*.json. Do not edit by hand.",
  'import type { RawSpec } from "./types";',
  "",
  ...files.map((f, i) => `import s${i} from "../../content/specs/${f}";`),
  ...(files.length ? [""] : []),
  `export const EXTRA_SPECS: readonly RawSpec[] = [${files.map((_, i) => `s${i} as unknown as RawSpec`).join(", ")}];`,
  "",
];
const out = lines.join("\n");
const target = join(root, "src", "content", "extra-specs.ts");

if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(target, "utf8");
  } catch {}
  if (cur !== out) {
    console.error("build-catalogue: src/content/extra-specs.ts is out of date; run node scripts/build-catalogue.mjs");
    process.exit(1);
  }
  console.log(`build-catalogue: up to date (${files.length} specs)`);
} else {
  writeFileSync(target, out);
  console.log(`build-catalogue: wrote ${files.length} specs`);
}
